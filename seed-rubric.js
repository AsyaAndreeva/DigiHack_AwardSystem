async function updateRubric() {
  try {
    await sql`DELETE FROM rubric_criteria`;
    
    for (const c of criteria) {
      await sql`
        INSERT INTO rubric_criteria (category, description, criterion, max_score, scoring_guide, order_idx)
        VALUES (${c.category}, ${c.description}, ${c.criterion}, ${c.max_score}, ${c.scoring_guide}, ${c.order_idx})
      `;
    }
    console.log('Successfully granularized criteria schemas! Distributed descriptions natively.');
  } catch (err) {
    console.error(err);
  }
}
updateRubric();
